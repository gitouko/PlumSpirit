/// HZ-Chop's frequency (Hz) of key `key` (the Lua's `HZ_Map` for 0–127).
/// Keys 128–255 (256-Key Mode) continue the map's top octaves, where every
/// key is exactly twice the key an octave below.
pub fn hz_of(key: u8) -> f64 {
    let (mut k, mut f) = (key, 1.0);
    while usize::from(k) >= HZ_BITS.len() {
        k -= 12;
        f *= 2.0;
    }
    f64::from_bits(HZ_BITS[usize::from(k)]) * f
}

/// How the Gate of each chop is derived.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum HzMode {
    /// The Lua exactly: the fraction of the first BaseGate accumulates and
    /// picks ceil / floor, even after fStep has changed BaseGate.
    OriginalLua,
    /// PlumSpirit bonus: every chop ends at the rounded exact running position
    /// (Σ BaseGate), so the long-run average Gate equals BaseGate also while
    /// fStep changes it.
    HighPrecision,
}

pub const HZ_MODES: &[&str] = &[
    "Original Lua Compatibility",
    "High Precision (exact running position)",
];

/// The Lua's `BaseGate = (BPS · PPQ) / Hz` with `BPS = 1 / ticks_to_secs(PPQ)`:
/// `secs_per_ppq` is the song's seconds for its first PPQ ticks.
pub fn hz_base_gate(ppq: u64, secs_per_ppq: f64, hz: f64) -> f64 {
    let bps = 1.0 / secs_per_ppq;
    (bps * ppq as f64) / hz
}

/// Chops one note `[start, start + len)` into consecutive notes, calling
/// `emit(start, gate)` for each (stops early when `emit` returns false). The
/// last chop may end after the note (as in the Lua).
pub fn hz_chop_note(
    start: u64,
    len: u64,
    base_gate: f64,
    step: f64,
    mode: HzMode,
    mut emit: impl FnMut(u64, u64) -> bool,
) {
    let end = u128::from(start) + u128::from(len);
    let mut cur = u128::from(start);
    let mut base = base_gate;
    match mode {
        HzMode::OriginalLua => {
            // local frac = BaseGate - math.floor(BaseGate); local fracAcc = 0.0
            let frac = base - base.floor();
            let mut acc = 0.0f64;
            while cur < end {
                base += step;
                if base < 1.0 {
                    base = 1.0;
                }
                acc += frac;
                let g = if acc >= 1.0 {
                    acc -= 1.0;
                    base.ceil()
                } else {
                    base.floor()
                };
                let g = gate_ticks(g);
                if cur > u128::from(u64::MAX) || !emit(cur as u64, g) {
                    return;
                }
                cur += u128::from(g);
            }
        }
        HzMode::HighPrecision => {
            // Exact running position relative to the note's start.
            let mut pos = 0.0f64;
            let mut done = 0u128;
            while cur < end {
                base += step;
                if base < 1.0 {
                    base = 1.0;
                }
                pos += base;
                let target = pos.round().max(0.0);
                let target = if target >= u128::MAX as f64 {
                    u128::MAX
                } else {
                    target as u128
                };
                let g = target.saturating_sub(done).clamp(1, u128::from(u64::MAX)) as u64;
                if cur > u128::from(u64::MAX) || !emit(cur as u64, g) {
                    return;
                }
                cur += u128::from(g);
                done += u128::from(g);
            }
        }
    }
}

/// A Gate (≥ 1 already) as ticks, saturating.
fn gate_ticks(g: f64) -> u64 {
    if g >= u64::MAX as f64 {
        u64::MAX
    } else {
        (g as u64).max(1)
    }
}

/// An upper bound of the chops of a note of `len` ticks whose gates start at
/// `b0` and change by `step` per chop (never below 1 tick).
fn hz_max_chops(len: f64, b0: f64, step: f64) -> f64 {
    if len <= 0.0 {
        return 0.0;
    }
    // Every chop is ≥ 1 tick and ≥ floor(b0 + i·step) ≥ b0 + i·step − 1.
    if step >= 0.0 {
        let g = (b0 - 1.0).max(1.0);
        return (len / g).ceil() + 1.0;
    }
    let s = -step;
    // Chops while b0 − 1 − i·s ≥ 1: i ≤ k1.
    let k1 = ((b0 - 2.0) / s).floor().max(0.0);
    // Ticks covered by the first k1 chops (lower bound).
    let s1 = k1 * (b0 - 1.0) - s * k1 * (k1 + 1.0) / 2.0;
    if len > s1 {
        return k1 + (len - s1).ceil() + 1.0;
    }
    // Smallest k with k(b0 − 1) − s·k(k+1)/2 ≥ len: solve the quadratic.
    let a = s / 2.0;
    let b = -(b0 - 1.0 - s / 2.0);
    let disc = (b * b - 4.0 * a * len).max(0.0);
    ((-b - disc.sqrt()) / (2.0 * a)).ceil().max(1.0) + 1.0
}

