struct HzChop {
    /// BaseGate per key of the project's keyboard (fixed key: the same value
    /// for every key).
    gates: Vec<f64>,
    step: f64,
    mode: HzMode,
    keep_source: bool,
    /// Reach of the last chop past its note's end (preview window).
    behind: u64,
}

impl Kernel for HzChop {
    fn growth(&self) -> Growth {
        Growth::Expand(u64::MAX)
    }

    fn estimate(&self, s: &SourceStats) -> Estimate {
        let n = s.count as u64;
        if n == 0 {
            return Estimate::for_notes(0, 0);
        }
        // The smallest first gate among the keys in the source.
        let b0 = (s.min_pitch..=s.max_pitch)
            .filter(|&p| s.pitch_hist[usize::from(p)] > 0)
            .map(|p| self.gates[usize::from(p)])
            .fold(f64::INFINITY, f64::min);
        let b0 = if b0.is_finite() { b0 } else { 1.0 };
        let sum = s.sum_dur as f64;
        let chops = if self.step >= 0.0 {
            // Concave in the length: the bound per tick holds for the sum.
            hz_max_chops(sum, b0, self.step) + n as f64
        } else {
            // Convex in the length: Σ f(len) ≤ (Σ len / max) · f(max).
            let max = (s.max_dur as f64).max(1.0);
            (sum / max).ceil() * hz_max_chops(max, b0, self.step) + n as f64
        };
        let mut out = if chops >= u64::MAX as f64 {
            u64::MAX
        } else {
            chops.ceil() as u64
        };
        if self.keep_source {
            out = out.saturating_add(n);
        }
        Estimate::for_notes(n, out)
    }

    fn as_point(&self) -> Option<&dyn PointKernel> {
        Some(self)
    }
}

impl PointKernel for HzChop {
    fn map(&self, n: &TNote, out: &mut Output) {
        if self.keep_source && !out.push(*n) {
            return;
        }
        let g = self.gates[usize::from(n.pitch)];
        hz_chop_note(n.start, n.dur, g, self.step, self.mode, |start, gate| {
            out.emit(
                i128::from(start),
                i128::from(gate),
                i64::from(n.pitch),
                i64::from(n.vel),
                n,
            )
        });
    }

    fn source_window(&self, t0: u64, t1: u64) -> (u64, u64) {
        (t0.saturating_sub(self.behind), t1)
    }
}

fn hz_build(p: &Params, b: &BuildCtx) -> Result<Box<dyn Kernel>, TransformError> {
    let inote = p.int("inote");
    let top = b.ctx.keys.max_pitch();
    if !(-1..=i64::from(top)).contains(&inote) {
        return Err(TransformError::Invalid(format!(
            "The key to chop to must be −1 (each note's own key) or 0 to {top}."
        )));
    }
    let step = p.float("fstep");
    if !step.is_finite() || !(-50.0..=50.0).contains(&step) {
        return Err(TransformError::Invalid(
            "The gate step must be between −50 and 50 ticks.".into(),
        ));
    }
    let ppq = b.ctx.ppq.max(1);
    // ticks_to_secs(PPQ): the song's first quarter note, from tick 0.
    let secs = b.ctx.seconds_at(ppq);
    if !(secs.is_finite() && secs > 0.0) {
        return Err(TransformError::Invalid(
            "The tempo at the start of the song gives no duration for a quarter note.".into(),
        ));
    }
    // One gate per key of the keyboard (and of every source pitch).
    let mut gates = vec![0.0f64; b.ctx.keys.keys().max(usize::from(b.stats.max_pitch) + 1)];
    for (k, g) in gates.iter_mut().enumerate() {
        let key = if inote < 0 { k as u8 } else { inote as u8 };
        *g = hz_base_gate(ppq, secs, hz_of(key));
    }
    let max_gate = gates.iter().copied().fold(1.0f64, f64::max);
    let max_dur = b.stats.max_dur as f64;
    // Last gate ≤ b0 + step + √(2 · len · step) for growing gates.
    let reach = max_gate + step.max(0.0) + (2.0 * max_dur * step.max(0.0)).sqrt() + 2.0;
    let behind = if reach >= u64::MAX as f64 {
        u64::MAX
    } else {
        reach.ceil() as u64
    };
    let mode = if p.choice("mode") == 1 {
        HzMode::HighPrecision
    } else {
        HzMode::OriginalLua
    };
    boxed(HzChop {
        gates,
        step,
        mode,
        keep_source: !p.flag("replace"),
        behind,
    })
}

