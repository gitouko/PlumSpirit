/// What SAFOR removed (shown in the window).
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct SaforStats {
    pub input: u64,
    pub duplicates_removed: u64,
    /// Sustains pass: notes it shortened, split or covered completely, and
    /// the pieces those notes became.
    pub fragments_from: u64,
    pub fragments: u64,
    pub quiet_removed: u64,
    pub output: u64,
}

impl SaforStats {
    pub fn message(&self) -> String {
        let g = crate::midi::group_digits;
        let mut s = String::new();
        if self.quiet_removed > 0 || (self.duplicates_removed == 0 && self.fragments_from == 0) {
            s.push_str(&format!("{} quiet note(s) removed.", g(self.quiet_removed)));
        }
        if self.duplicates_removed > 0 {
            s.push_str(&format!(
                "{} doubled note(s) removed.",
                g(self.duplicates_removed)
            ));
        }
        if self.fragments_from > 0 {
            if !s.is_empty() {
                s.push(' ');
            }
            s.push_str(&format!(
                "{} overlapped note(s) cut to {} piece(s).",
                g(self.fragments_from),
                g(self.fragments)
            ));
        }
        s
    }
}

/// SAFOR's per-note "track" number: the document track (slot order) and MIDI
/// channel, like `channel | (track << 4)` upstream — later tracks and higher
/// channels rank higher.
#[inline]
fn safor_rank(src: &Source, n: &TNote) -> u64 {
    let index = src.track(n.track).map(|t| t.index as u64).unwrap_or(0);
    (index << 4) | u64::from(n.ch & 15)
}

/// SAFOR's `priority_predicate(O, N)`: whether the new note `n` replaces the
/// kept note `o` of the same tick and key.
#[inline]
fn safor_replaces(o_rank: u64, o_len: u64, n_rank: u64, n_len: u64) -> bool {
    !(n_rank >= o_rank && n_len < o_len)
}

/// Overlaps removal. Returns the surviving notes (with raised velocities) in
/// SAFOR's push order within each (start, key), and the number removed.
pub fn safor_overlaps(src: &Source, notes: &[TNote]) -> (Vec<TNote>, u64) {
    // Push order: SAFOR reads track by track and keeps a note when its note-off
    // is read: (rank's track, end tick, channel) — ties by pitch and start.
    let mut order: Vec<usize> = (0..notes.len()).collect();
    order.sort_unstable_by_key(|&i| {
        let n = &notes[i];
        (n.start, n.pitch, safor_rank(src, n) >> 4, n.end(), n.ch, i)
    });
    let mut out = Vec::with_capacity(notes.len());
    let mut removed = 0u64;
    let mut kept: Vec<(usize, u64, u8)> = Vec::new(); // (index, rank, velocity)
    let mut i = 0;
    while i < order.len() {
        let (s, p) = (notes[order[i]].start, notes[order[i]].pitch);
        let mut j = i;
        while j < order.len() && notes[order[j]].start == s && notes[order[j]].pitch == p {
            j += 1;
        }
        kept.clear();
        for &k in &order[i..j] {
            let n = &notes[k];
            let rank = safor_rank(src, n);
            let mut vel = n.vel;
            kept.retain(|&(o, o_rank, o_vel)| {
                if safor_replaces(o_rank, notes[o].dur, rank, n.dur) {
                    vel = vel.max(o_vel);
                    removed += 1;
                    false
                } else {
                    true
                }
            });
            kept.push((k, rank, vel));
        }
        for &(k, _, vel) in &kept {
            let mut n = notes[k];
            n.vel = vel;
            out.push(n);
        }
        i = j;
    }
    (out, removed)
}

/// Sustains removal on the survivors of [`safor_overlaps`] (in its order): per
/// key, every tick belongs to the last note (in that order) covering it; the
/// timeline is cut wherever the owner changes or a note starts. A piece keeps
/// its owner's Track / Subchannel / channel / group, the loudest velocity of the
/// notes starting at its first tick, or velocity 1 when it continues a note
/// (SAFOR writes 0 → 1). Returns (pieces, notes changed = shortened / split /
/// covered, pieces of the changed notes).
pub fn safor_sustains(survivors: &[TNote]) -> (Vec<TNote>, u64, u64) {
    use std::collections::BinaryHeap;
    // Per key, order = position in `survivors` within the key (already in
    // (start, push) order per (start, key)), sorted by start.
    // One list per key up to the highest one used (any key range; v0.8
    // masked the pitch to 7 bits).
    let keys = survivors
        .iter()
        .map(|n| usize::from(n.pitch) + 1)
        .max()
        .unwrap_or(0);
    let mut by_key: Vec<Vec<usize>> = vec![Vec::new(); keys];
    for (i, n) in survivors.iter().enumerate() {
        by_key[usize::from(n.pitch)].push(i);
    }
    let mut out = Vec::with_capacity(survivors.len());
    let mut cut = 0u64;
    let mut pieces_from_cut = 0u64;
    // Identity of an owner (SAFOR: track | channel; PlumSpirit adds the
    // subchannel and group so artwork is not merged across them).
    let ident = |n: &TNote| (n.track, n.ch, n.sub, n.group, n.flags);
    for list in by_key.iter_mut() {
        if list.is_empty() {
            continue;
        }
        list.sort_by_key(|&i| (survivors[i].start, i));
        // Event points: every start and end.
        let mut points: Vec<u64> = Vec::with_capacity(list.len() * 2);
        for &i in list.iter() {
            points.push(survivors[i].start);
            points.push(survivors[i].end());
        }
        points.sort_unstable();
        points.dedup();
        // Sweep: active notes by order (max-heap on the order key).
        let mut heap: BinaryHeap<(u64, usize)> = BinaryHeap::new(); // (order, index)
        let mut next = 0usize;
        // The piece being built: (owner index, start tick, velocity).
        let mut cur: Option<(usize, u64, u8)> = None;
        // Per note: pieces it owns, and whether its only piece is itself.
        let mut pieces_of: Vec<u32> = vec![0; list.len()];
        let mut exact: Vec<bool> = vec![false; list.len()];
        for &t in &points {
            // Notes starting at t (several: the loudest velocity, the last owns).
            let mut start_vel = 0u8;
            let mut starts_here = false;
            while next < list.len() && survivors[list[next]].start == t {
                let i = list[next];
                start_vel = start_vel.max(survivors[i].vel);
                heap.push((next as u64, next));
                starts_here = true;
                next += 1;
            }
            // Drop notes that ended at or before t.
            while let Some(&(_, pos)) = heap.peek() {
                if survivors[list[pos]].end() <= t {
                    heap.pop();
                } else {
                    break;
                }
            }
            let owner = heap.peek().map(|&(_, pos)| pos);
            let same = match (cur, owner) {
                (Some((c, _, _)), Some(o)) => {
                    ident(&survivors[list[c]]) == ident(&survivors[list[o]])
                }
                _ => false,
            };
            if starts_here || !same {
                if let Some((c, s0, v)) = cur.take() {
                    let n = survivors[list[c]];
                    let mut piece = n;
                    piece.start = s0;
                    piece.dur = t - s0;
                    piece.vel = v.max(1);
                    exact[c] = piece == n;
                    out.push(piece);
                    pieces_of[c] += 1;
                }
                if let Some(o) = owner {
                    let v = if starts_here { start_vel } else { 0 };
                    cur = Some((o, t, v));
                }
            }
        }
        // `points` ends with the last end: nothing stays open.
        debug_assert!(cur.is_none() || heap.is_empty());
        for (&c, &same) in pieces_of.iter().zip(&exact) {
            if !(c == 1 && same) {
                cut += 1;
                pieces_from_cut += u64::from(c);
            }
        }
    }
    (out, cut, pieces_from_cut)
}

fn safor_build(p: &Params, _b: &BuildCtx) -> Result<Box<dyn Kernel>, TransformError> {
    let mode = p.choice("mode");
    let threshold = p.int("threshold").clamp(0, 127) as u8;
    boxed(Contextual {
        f: move |src: &Source, out: &mut Output| {
            let mut st = SaforStats {
                input: src.notes.len() as u64,
                ..Default::default()
            };
            // Muted notes take no part (they do not sound); they are kept.
            let (muted, live): (Vec<TNote>, Vec<TNote>) = src.notes.iter().partition(|n| n.muted());
            for n in &muted {
                out.push(*n);
            }
            let result = if mode == 2 {
                let kept: Vec<TNote> = live.into_iter().filter(|n| n.vel >= threshold).collect();
                st.quiet_removed = (src.notes.len() - muted.len() - kept.len()) as u64;
                kept
            } else {
                let (survivors, removed) = safor_overlaps(src, &live);
                st.duplicates_removed = removed;
                if mode == 1 {
                    let (pieces, cut, from) = safor_sustains(&survivors);
                    st.fragments_from = cut;
                    st.fragments = from;
                    pieces
                } else {
                    survivors
                }
            };
            for n in result {
                out.push(n);
                out.check()?;
            }
            st.output = out.len() as u64;
            out.message = Some(st.message());
            Ok(())
        },
        // Sustains removal cuts each key's timeline at note starts and ends:
        // fewer pieces than twice the notes.
        growth: Growth::Expand(2),
        estimate: None,
    })
}
