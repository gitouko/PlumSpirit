import csv
import datetime
import json
import os
import re
import subprocess
import sys
import tomllib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REQ_STATES = ("NOT_STARTED", "IN_PROGRESS", "DONE", "BLOCKED", "NEEDS_VERIFICATION", "INVALIDATED")
SLICE_STATES = ("PLANNED", "ACTIVE", "DONE")
EVIDENCE_KINDS = ("test", "bench", "review", "reference", "manual", "gate", "sync")
EVIDENCE_RESULTS = ("pass", "fail", "info", "not_measured")
DOC_SUFFIXES = (".md", ".txt", ".png", ".jpg", ".csv")
BENCH_HEADER = ["date", "commit", "machine", "operation", "fixture", "notes", "elapsed_ms",
                "peak_rss_mb", "cpu", "fps", "underruns", "output_count", "command"]
FUNC_STATES = ("PROPOSED", "APPROVED", "IMPLEMENTED", "VERIFIED")
# Catalog categories of tools that are Legacy as a whole (LEGACY_MAP [[legacy]] without function).
LEGACY_CATEGORIES = ("one-click", "legacy", "legacy-experimental")
# V09-S32 design fields of a new function (docs/v0_9/TOOL_DESIGN.md).
RUBRIC_KEYS = ("distinct", "black_midi", "depth", "experiment", "interaction", "perf", "preview", "test")
GROWTH_KINDS = ("Map", "Thin", "Expand", "Add", "Generate")
PREVIEW_KINDS = ("Viewport", "Worker", "ParamDependent")
PURPOSE_TARGETS = ("time", "gate", "pitch", "velocity", "count", "order", "subchannel", "channel",
                   "structure", "control")
RESERVED_PURPOSES = ("subchannel:offset-driver", "pitch:offset-driver", "count:overlap-removal",
                     "control:sweep")
SHARED_HELPERS = ("euclid", "tempo_time", "metric_position", "chord_groups", "phrase_detect",
                  "density_window", "scale_lattice", "seeded_stream")
RUBRIC_MIN_TOTAL = 16
# "Name (Type …)" — the parameter vocabulary of transform/param.rs.
CONTROL_RE = re.compile(r"^(.+?) \((Int|Float|Bool|Choice|Ticks|Pitch|Curve|List|Seed|Text)\b")
SWEEPABLE = ("Int", "Float", "Ticks", "Pitch")


def read(p):
    with open(p, encoding="utf-8") as f:
        return f.read()


def write(p, text):
    with open(p, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def ev_reqs(e):
    """Requirement ids of an evidence record (old records used `reqs`)."""
    return e.get("requirement_ids", e.get("reqs", []))


class Plan:
    def __init__(self, root, vdir):
        self.root, self.dir, self.vdir = root, os.path.join(root, vdir), vdir
        self.graph = self._toml("REQ_GRAPH.toml")
        self.impact = self._toml("TEST_IMPACT.toml")
        self.catalog = self._toml("TOOL_CATALOG.toml", optional=True)
        self.legacy = self._toml("LEGACY_MAP.toml", optional=True)
        self.evidence = self._jsonl("EVIDENCE.jsonl")
        p = os.path.join(self.dir, "CURRENT_SLICE.md")
        self.slice_md = read(p) if os.path.exists(p) else ""

    def _toml(self, name, optional=False):
        p = os.path.join(self.dir, name)
        if optional and not os.path.exists(p):
            return {}
        with open(p, "rb") as f:
            return tomllib.load(f)

    def _jsonl(self, name):
        p = os.path.join(self.dir, name)
        out = []
        if os.path.exists(p):
            for n, line in enumerate(read(p).splitlines(), 1):
                if line.strip():
                    try:
                        out.append(json.loads(line))
                    except json.JSONDecodeError as e:
                        out.append({"_error": f"EVIDENCE.jsonl line {n}: {e}"})
        return out

    @property
    def meta(self):
        return self.graph.get("meta", {})

    @property
    def reqs(self):
        return self.graph.get("req", {})

    @property
    def slices(self):
        return self.graph.get("slice", {})

    def evidence_for(self, rid):
        return [e for e in self.evidence if rid in ev_reqs(e)]

    # ---------------------------------------------------------------- check
    def check(self):
        errs = []
        for k in ("version", "active_slice", "canonical_repo"):
            if k not in self.meta:
                errs.append(f"meta.{k} missing")
        for sid, s in self.slices.items():
            if s.get("status") not in SLICE_STATES:
                errs.append(f"slice {sid}: status {s.get('status')!r} not in {SLICE_STATES}")
            if not s.get("title"):
                errs.append(f"slice {sid}: title missing")
        active = self.meta.get("active_slice")
        complete = bool(self.reqs) and all(r.get("status") == "DONE" for r in self.reqs.values()) \
            and all(s.get("status") == "DONE" for s in self.slices.values())
        if active not in self.slices:
            errs.append(f"meta.active_slice {active!r} is not a slice")
        elif self.slices[active].get("status") != "ACTIVE" and not complete:
            errs.append(f"active slice {active} has status {self.slices[active].get('status')}")
        m = re.search(r"^Slice:\s*(\S+)", self.slice_md, re.M)
        if not m:
            errs.append("CURRENT_SLICE.md has no 'Slice: <id>' line")
        elif m.group(1) != active:
            errs.append(f"CURRENT_SLICE.md is slice {m.group(1)}, meta.active_slice is {active}")
        if sum(1 for s in self.slices.values() if s.get("status") == "ACTIVE") > 1:
            errs.append("more than one ACTIVE slice (one atomic slice at a time)")
        ev_ids = set()
        for e in self.evidence:
            if "_error" in e:
                errs.append(e["_error"])
                continue
            eid = e.get("id")
            if eid in ev_ids:
                errs.append(f"evidence {eid}: duplicate id")
            ev_ids.add(eid)
            if e.get("kind") not in EVIDENCE_KINDS:
                errs.append(f"evidence {eid}: kind {e.get('kind')!r}")
            if e.get("result") not in EVIDENCE_RESULTS:
                errs.append(f"evidence {eid}: result {e.get('result')!r}")
            for r in ev_reqs(e):
                if r not in self.reqs:
                    errs.append(f"evidence {eid}: unknown requirement {r}")
        for rid, r in self.reqs.items():
            st = r.get("status")
            if st not in REQ_STATES:
                errs.append(f"{rid}: status {st!r} not in {REQ_STATES}")
            for k in ("name", "text"):
                if not r.get(k):
                    errs.append(f"{rid}: {k} missing")
            if r.get("slice") not in self.slices:
                errs.append(f"{rid}: slice {r.get('slice')!r} unknown")
            for d in r.get("dependencies", []):
                if d not in self.reqs:
                    errs.append(f"{rid}: dependency {d} unknown")
            for e in r.get("acceptance_evidence", []):
                if e not in ev_ids:
                    errs.append(f"{rid}: acceptance evidence {e} unknown")
            if st == "BLOCKED" and not r.get("blocked"):
                errs.append(f"{rid}: BLOCKED without a `blocked` reason")
            if st == "DONE":
                ev = self.evidence_for(rid)
                if not r.get("evidence_waived"):
                    if not any(e.get("result") == "pass" for e in ev):
                        errs.append(f"{rid}: DONE without passing evidence")
                    if r.get("perf") and not any(e.get("kind") == "bench" for e in ev):
                        errs.append(f"{rid}: performance-sensitive and DONE without bench evidence")
                    if not r.get("tests"):
                        errs.append(f"{rid}: DONE without tests listed")
                for d in r.get("dependencies", []):
                    if self.reqs.get(d, {}).get("status") != "DONE":
                        errs.append(f"{rid}: DONE but dependency {d} is not")
        for sid, sl in self.slices.items():
            if sl.get("status") == "DONE":
                for rid, r in self.reqs.items():
                    if r.get("slice") == sid and r.get("status") not in ("DONE", "INVALIDATED"):
                        errs.append(f"slice {sid} is DONE but {rid} is {r.get('status')}")
        errs += self._cycles()
        for i, rule in enumerate(self.impact.get("rule", [])):
            if not rule.get("paths") or not (rule.get("fast") or rule.get("heavy") or rule.get("none")):
                errs.append(f"TEST_IMPACT rule {i} ({rule.get('name')}): needs paths and fast / heavy (or none = true)")
        for g in ("integration", "release"):
            if not self.impact.get("gates", {}).get(g, {}).get("cmds"):
                errs.append(f"TEST_IMPACT gates.{g}.cmds missing")
        eo = self.meta.get("execution_order")
        if eo is not None:
            if sorted(eo) != sorted(self.slices) or len(eo) != len(set(eo)):
                errs.append("meta.execution_order must list every slice exactly once")
        errs += self.check_catalog()
        errs += self.check_csv()
        return errs

    def _cycles(self):
        state, errs = {}, []

        def visit(n, path):
            if state.get(n) == 1:
                errs.append("dependency cycle: " + " -> ".join(path + [n]))
                return
            if state.get(n) == 2 or n not in self.reqs:
                return
            state[n] = 1
            for d in self.reqs[n].get("dependencies", []):
                visit(d, path + [n])
            state[n] = 2

        for n in self.reqs:
            visit(n, [])
        return errs

    def check_csv(self):
        errs = []
        for name in ("BENCH_RESULTS.csv", "PERFORMANCE_BASELINE.csv"):
            p = os.path.join(self.dir, name)
            if os.path.exists(p):
                rows = list(csv.reader(read(p).splitlines()))
                if not rows or rows[0] != BENCH_HEADER:
                    errs.append(f"{name}: header must be {','.join(BENCH_HEADER)}")
                for n, row in enumerate(rows[1:], 2):
                    if len(row) != len(BENCH_HEADER):
                        errs.append(f"{name} line {n}: {len(row)} fields")
        return errs

    # -------------------------------------------------------------- catalog
    def check_catalog(self):
        """Schema of TOOL_CATALOG / LEGACY_MAP (counts are the --gate check)."""
        errs, fids, tids = [], set(), set()
        for t in self.catalog.get("tool", []):
            tid = t.get("id")
            if not tid or tid in tids:
                errs.append(f"TOOL_CATALOG: tool id {tid!r} missing or duplicate")
            tids.add(tid)
            for k in ("name", "family", "category", "rule"):
                if k not in t:
                    errs.append(f"TOOL_CATALOG {tid}: {k} missing")
            for f in t.get("function", []):
                fid = f.get("id")
                key = (tid, fid)
                if not fid or key in fids:
                    errs.append(f"TOOL_CATALOG {tid}: function id {fid!r} missing or duplicate")
                fids.add(key)
                if f.get("state", "PROPOSED") not in FUNC_STATES:
                    errs.append(f"TOOL_CATALOG {tid}/{fid}: state {f.get('state')!r}")
                if f.get("status") not in ("active", "legacy"):
                    errs.append(f"TOOL_CATALOG {tid}/{fid}: status must be active or legacy")
                if not f.get("name"):
                    errs.append(f"TOOL_CATALOG {tid}/{fid}: name missing")
                if f.get("origin") == "new":
                    errs += self.check_design(tid, f)
                elif f.get("purpose") is not None:
                    target, _, mech = str(f["purpose"]).partition(":")
                    if target not in PURPOSE_TARGETS or not mech:
                        errs.append(f"TOOL_CATALOG {tid}/{fid}: purpose {f['purpose']!r} is not target:mechanism")
            purposes = [f.get("purpose") for f in t.get("function", [])
                        if f.get("status") == "active" and f.get("purpose")]
            dup = sorted({x for x in purposes if purposes.count(x) > 1})
            if dup:
                errs.append(f"TOOL_CATALOG {tid}: functions share a purpose {dup}")
            used = {f.get("id") for f in t.get("function", [])}
            back = sorted(used & set(t.get("retired", [])))
            if back:
                errs.append(f"TOOL_CATALOG {tid}: retired function ids reused {back}")
            orders = [f.get("order") for f in t.get("function", []) if f.get("origin") == "new"]
            dup = sorted({x for x in orders if orders.count(x) > 1})
            if dup:
                errs.append(f"TOOL_CATALOG {tid}: new functions share a composition order {dup}")
        # §109–§114 (V09-S33): whole-tool entries are the One-Click / Legacy
        # tools, entries naming a function are that tool's legacy functions.
        cats = {t.get("id"): t.get("category") for t in self.catalog.get("tool", [])}
        status = {(t.get("id"), f.get("id")): f.get("status")
                  for t in self.catalog.get("tool", []) for f in t.get("function", [])}
        whole = set()
        for lg in self.legacy.get("legacy", []):
            tid, fid = lg.get("tool"), lg.get("function")
            if tid not in tids:
                errs.append(f"LEGACY_MAP: legacy tool {tid!r} not in TOOL_CATALOG")
            elif fid is None:
                whole.add(tid)
                if cats.get(tid) not in LEGACY_CATEGORIES:
                    errs.append(f"LEGACY_MAP: legacy tool {tid} has category {cats.get(tid)!r} in TOOL_CATALOG")
            elif status.get((tid, fid)) != "legacy":
                errs.append(f"LEGACY_MAP: legacy function {tid}/{fid} is not a legacy function in TOOL_CATALOG")
        for tid, cat in cats.items():
            if cat in LEGACY_CATEGORIES and tid not in whole:
                errs.append(f"TOOL_CATALOG {tid}: category {cat} without a LEGACY_MAP [[legacy]] entry")
        for rm in self.legacy.get("removed", []):
            if rm.get("tool") in tids and any(t.get("id") == rm.get("tool") and t.get("category") != "removed"
                                              for t in self.catalog.get("tool", [])):
                errs.append(f"LEGACY_MAP: removed tool {rm.get('tool')} is still listed as usable")
        return errs

    @staticmethod
    def check_design(tid, f):
        """A new function's design fields (V09-S32, docs/v0_9/TOOL_DESIGN.md)."""
        errs, at = [], f"TOOL_CATALOG {tid}/{f.get('id')}"
        for k in ("summary", "controls", "sweeps", "growth", "preview", "purpose", "rubric", "params", "order"):
            if k not in f:
                errs.append(f"{at}: design field {k} missing")
        if errs:
            return errs
        kinds = {}
        if not isinstance(f["controls"], list) or not f["controls"]:
            errs.append(f"{at}: controls must be a non-empty list")
        else:
            if f["params"] != len(f["controls"]):
                errs.append(f"{at}: params {f['params']} != {len(f['controls'])} controls")
            for c in f["controls"]:
                m = CONTROL_RE.match(str(c))
                if not m:
                    errs.append(f"{at}: control {c!r} is not 'Name (Type …)' with a param.rs type")
                elif m.group(1) in kinds:
                    errs.append(f"{at}: control name {m.group(1)!r} twice")
                else:
                    kinds[m.group(1)] = m.group(2)
        if not isinstance(f["sweeps"], list):
            errs.append(f"{at}: sweeps must be a list")
        else:
            for w in f["sweeps"]:
                if kinds and kinds.get(w) not in SWEEPABLE:
                    errs.append(f"{at}: sweep target {w!r} is not a numeric control of the function")
        if f["growth"] not in GROWTH_KINDS:
            errs.append(f"{at}: growth {f['growth']!r}")
        if f["preview"] not in PREVIEW_KINDS:
            errs.append(f"{at}: preview {f['preview']!r}")
        if not (100 < f["order"] < 900):
            errs.append(f"{at}: order {f['order']} outside the new-function slots 110-790")
        target, _, mech = str(f["purpose"]).partition(":")
        if target not in PURPOSE_TARGETS or not mech:
            errs.append(f"{at}: purpose {f['purpose']!r} is not target:mechanism")
        if f["purpose"] in RESERVED_PURPOSES:
            errs.append(f"{at}: purpose {f['purpose']} belongs to a mandatory service")
        if mech.endswith("random") and tid != "randomize":
            errs.append(f"{at}: a generic random purpose outside the Randomizer")
        for h in f.get("shared", []):
            if h not in SHARED_HELPERS:
                errs.append(f"{at}: unknown shared helper {h!r}")
        r = f["rubric"]
        if not isinstance(r, dict) or set(r) != set(RUBRIC_KEYS) or any(
                not isinstance(v, int) or not 0 <= v <= 3 for v in r.values()):
            errs.append(f"{at}: rubric needs {', '.join(RUBRIC_KEYS)} scored 0-3")
        else:
            total = sum(r.values())
            n = len(f["sweeps"]) if isinstance(f["sweeps"], list) else 0
            if r["interaction"] > (0 if n == 0 else 2 if n == 1 else 3):
                errs.append(f"{at}: interaction {r['interaction']} with {n} sweep target(s) "
                            "(1-2 need a sweep target, 3 needs two)")
            if r["preview"] != {"Viewport": 3, "ParamDependent": 2, "Worker": 1}.get(f["preview"], r["preview"]):
                errs.append(f"{at}: preview score {r['preview']} does not match preview {f['preview']}")
            if total < RUBRIC_MIN_TOTAL or r["distinct"] < 2:
                errs.append(f"{at}: rubric {total}/24, distinct {r['distinct']} (needs >= {RUBRIC_MIN_TOTAL}, distinct >= 2)")
        return errs

    @staticmethod
    def name_tokens(name):
        """Significant words of a function name (lower case, plural / -ing / -ed
        folded) for the similarity review."""
        stop = {"the", "and", "for", "per", "from", "with", "into", "across", "along", "each", "every"}
        out = set()
        for w in re.findall(r"[a-z0-9]+", name.lower()):
            if len(w) < 3 or w in stop:
                continue
            for suf in ("ing", "ed", "es", "s"):
                if w.endswith(suf) and len(w) - len(suf) >= 4:
                    w = w[: -len(suf)]
                    break
            out.add(w)
        return out

    def catalog_review(self, similar=0.67):
        """The no-duplicate review input (V09-S32 step 8): rubric summary per
        tool; purposes shared inside a family (SHARED) and across families
        (SHARED-X); the same name in two tools (SAME NAME, an error in
        review); names of a new function and any other tool's active function
        whose significant words overlap at least `similar` (SIMILAR)."""
        by, lines, funcs = {}, [], []
        for t in self.catalog.get("tool", []):
            new = [f for f in t.get("function", []) if f.get("origin") == "new"]
            if new:
                tot = [sum(f["rubric"].values()) for f in new if isinstance(f.get("rubric"), dict)]
                lines.append(f"{t['id']:<22} {len(new):>2} new · rubric mean {sum(tot) / len(tot):.1f} min {min(tot)}")
            for f in t.get("function", []):
                if f.get("status") != "active" or f.get("origin") == "mandatory":
                    continue
                funcs.append((t["id"], t.get("family"), f))
                if f.get("purpose") and (f.get("origin") == "new" or any(
                        g.get("origin") == "new" for g in t.get("function", []))):
                    by.setdefault(f["purpose"], []).append((t["id"], t.get("family"), f.get("origin")))
        for purpose, users in sorted(by.items()):
            tools = sorted({u[0] for u in users})
            if len(tools) > 1 and any(u[2] == "new" for u in users):
                fams = sorted({str(u[1]) for u in users})
                tag = "SHARED" if len(fams) == 1 else "SHARED-X"
                lines.append(f"{tag} {'/'.join(fams)} {purpose}: {', '.join(tools)}")
        names = {}
        for tid, _, f in funcs:
            names.setdefault(f["name"].lower(), []).append((tid, f.get("origin")))
        for name, users in sorted(names.items()):
            if len({u[0] for u in users}) > 1 and any(u[1] == "new" for u in users):
                lines.append(f"SAME NAME {name!r}: {', '.join(u[0] for u in users)}")
        toks = [(tid, f, self.name_tokens(f["name"])) for tid, _, f in funcs]
        for i, (ta, fa, wa) in enumerate(toks):
            if fa.get("origin") != "new" or not wa:
                continue
            for tb, fb, wb in toks:
                if tb == ta or not wb or (fb.get("origin") == "new" and (tb, fb["id"]) < (ta, fa["id"])):
                    continue
                j = len(wa & wb) / len(wa | wb)
                if j >= similar and fa["name"].lower() != fb["name"].lower():
                    lines.append(f"SIMILAR {j:.2f} {ta}/{fa['id']} {fa['name']!r} ~ {tb}/{fb['id']} {fb['name']!r}")
        return lines

    def catalog_vs_registry(self, tsv):
        """Differences between the catalog's registry functions and a registry
        dump (`cargo run -p plumspirit_engine --example tool_catalog`). The
        registry lists a tool's v0.8 advanced functions — and, for a tool new
        in v0.9 such as Paste Repeat (notes), its contract functions."""
        reg, cur = {}, None
        for line in tsv.splitlines():
            f = line.split("\t")
            if f[0] == "TOOL":
                cur = reg.setdefault(f[1], [])
            elif f[0] == "ADV" and cur is not None:
                cur.append((f"a{int(f[1]):02d}", f[2]))
        errs = []
        cat = {t["id"]: t for t in self.catalog.get("tool", [])}
        for tid, funcs in reg.items():
            t = cat.get(tid)
            if not t:
                errs.append(f"registry tool {tid} missing from TOOL_CATALOG")
                continue
            if t.get("category") == "removed":
                continue
            have = {f["id"]: f.get("name") for f in t.get("function", [])
                    if f.get("origin") in ("v0.8", "contract")}
            for fid, name in funcs:
                if have.get(fid) != name:
                    errs.append(f"{tid}/{fid}: registry '{name}', catalog '{have.get(fid)}'")
        for tid, t in cat.items():
            if tid not in reg and any(f.get("origin") == "v0.8" for f in t.get("function", [])):
                errs.append(f"catalog tool {tid} not in the registry")
        return errs

    def catalog_counts(self):
        """(rows, gate errors) for §096–§100, §110, §150–§161, §253."""
        rows, errs = [], []
        tools = self.catalog.get("tool", [])
        for t in tools:
            act = [f for f in t.get("function", []) if f.get("status") == "active"]
            impl = [f for f in act if f.get("state") in ("IMPLEMENTED", "VERIFIED")]
            rule = t.get("rule")
            rows.append((t["id"], t.get("category"), rule, len(act), len(impl)))
            # A tool whose 25 are the contract's own (c01 – c25: generators,
            # Tumours) counts them without the platform's mandatory ones
            # (§096); the v0.7 tools' 25 include them.
            own = [f for f in act if f.get("origin") != "mandatory"]
            count = act if not any(f.get("origin") == "contract" for f in act) else own
            # v1.0-beta1 contract additions (origin "v1.0-beta1", e.g. Note
            # Properties' Experimental math expressions, §010) are features the
            # beta1 contract adds on top of the v0.9 §253 quota of 25.
            count = [f for f in count if f.get("origin") != "v1.0-beta1"]
            if rule == "25" and len(count) != 25:
                errs.append(f"{t['id']}: {len(count)} active advanced functions, need 25")
            if rule == "fixed" and len(act) != t.get("expected", -1):
                errs.append(f"{t['id']}: {len(act)} active functions, need {t.get('expected')}")
            if rule == "one-click" and act:
                errs.append(f"{t['id']}: one-click tool with {len(act)} advanced functions")
            names = [" ".join(f.get("name", "").split()) for f in act]
            dup = {n for n in names if names.count(n) > 1}
            if dup:
                errs.append(f"{t['id']}: duplicate function names {sorted(dup)}")
        exp = [t for t in tools if t.get("category") == "experimental"]
        if self.catalog.get("experimental_active_count") is not None and len(exp) != self.catalog["experimental_active_count"]:
            errs.append(f"{len(exp)} active Experimental tools, need {self.catalog['experimental_active_count']}")
        for kind, want in (("generator-simple", 5), ("generator-advanced", 5)):
            n = sum(1 for t in tools if t.get("category") == kind)
            if n != want:
                errs.append(f"{n} {kind} tools, need {want}")
        return rows, errs

    # --------------------------------------------------------------- impact
    def impact_for(self, paths):
        fast, heavy, bench, unmapped = [], [], [], []
        rules = self.impact.get("rule", [])
        for p in paths:
            p = p.replace("\\", "/")
            hit = [r for r in rules if any(p.startswith(pre) for pre in r["paths"])]
            if not hit:
                if p.endswith(DOC_SUFFIXES):
                    continue
                unmapped.append(p)
                hit = [r for r in rules if r.get("name") == self.impact.get("fallback")]
            for r in hit:
                for key, out in (("fast", fast), ("heavy", heavy), ("bench", bench)):
                    for c in r.get(key, []):
                        if c not in out:
                            out.append(c)
        return fast, heavy, bench, unmapped

    def ready(self):
        return [rid for rid, r in self.reqs.items() if r.get("status") == "NOT_STARTED"
                and all(self.reqs.get(d, {}).get("status") == "DONE" for d in r.get("dependencies", []))]

    def entry(self, rid):
        r = self.reqs[rid]
        L = [f"[{rid}] {r.get('name')} — {r.get('status')} (slice {r.get('slice')}"
             + (", perf" if r.get("perf") else "") + ")",
             f"  contract: {', '.join(r.get('contract', [])) or '—'}; deps: {', '.join(r.get('dependencies', [])) or '—'}"]
        if r.get("source_modules"):
            L.append(f"  modules: {', '.join(r['source_modules'])}")
        L.append("  " + " ".join(r.get("text", "").split()))
        if r.get("tests"):
            L.append("  tests: " + "; ".join(r["tests"]))
        if r.get("reference_evidence"):
            L.append("  refs: " + ", ".join(r["reference_evidence"]))
        if r.get("blocked"):
            L.append("  blocked: " + r["blocked"])
        ev = self.evidence_for(rid)
        if ev:
            L.append("  evidence: " + ", ".join(f"{e['id']} {e['kind']} {e['result']}" for e in ev[-4:]))
        return "\n".join(L)

    # -------------------------------------------------------------- capsule
    @staticmethod
    def brief(text, n=320):
        """`text` cut at a word boundary near `n` characters (the capsule
        stays small; the full text is in EVIDENCE.jsonl / REQ_GRAPH.toml)."""
        t = " ".join((text or "").split())
        if len(t) <= n:
            return t
        cut = t.rfind(" ", 0, n)
        return t[: cut if cut > n // 2 else n] + " …"

    @staticmethod
    def outline(text):
        """`text` without its parenthesised details (the phase narrative's
        per-slice notes live in REQ_GRAPH.toml meta and the evidence)."""
        out, depth = [], 0
        for ch in text or "":
            if ch == "(":
                depth += 1
            elif ch == ")" and depth:
                depth -= 1
            elif not depth:
                out.append(ch)
        t = " ".join("".join(out).split())
        return re.sub(r"\s+([.,;])", r"\1", t)

    def capsule(self, git):
        m, active = self.meta, self.meta.get("active_slice")
        s = self.slices.get(active, {})
        counts = {}
        for r in self.reqs.values():
            counts[r.get("status")] = counts.get(r.get("status"), 0) + 1
        act = [rid for rid, r in self.reqs.items() if r.get("slice") == active]
        done_slices = [sid for sid, sl in self.slices.items() if sl.get("status") == "DONE"]
        L = [f"# SESSION CAPSULE — PlumSpirit v{m.get('version')}",
             "",
             f"Generated by `python3 tools/capsule.py capsule` — do not edit. App version "
             f"{git['app_version']}; branch `{git['branch']}` on `{git['head']}`.",
             "",
             "Read this, `CURRENT_SLICE.md`, then `python3 tools/capsule.py slice` (active entries). "
             "Not the contract, roadmap, finished research or old logs.",
             "",
             "## Phase",
             self.outline(m.get("phase", "")) + " (Details: REQ_GRAPH.toml `[meta] phase`.)",
             "",
             "Requirements: " + ", ".join(f"{k} {counts[k]}" for k in REQ_STATES if counts.get(k)),
             "",
             "## Dirty files at generation",
             (", ".join(f"`{f}`" for f in git["dirty"][:20]) + (f" … +{len(git['dirty']) - 20}" if len(git["dirty"]) > 20 else ""))
             if git["dirty"] else "none",
             "",
             f"## Current slice {active} — {s.get('title', '?')}",
             " ".join(s.get("goal", "").split()),
             ""]
        L += [f"* {rid} [{self.reqs[rid].get('status')}] {self.reqs[rid].get('name')}" for rid in act]
        files = s.get("files", [])
        if files:
            fast, heavy, bench, _ = self.impact_for(files)
            L += ["", "Targeted tests: " + "; ".join(f"`{c}`" for c in fast)]
            if bench:
                L.append("Benchmarks: " + "; ".join(f"`{c}`" for c in bench))
        nxt = re.search(r"^## NEXT EXACT ACTION\s*\n(.*?)(?=^## |\Z)", self.slice_md, re.M | re.S)
        L += ["", "## NEXT EXACT ACTION", (nxt.group(1).strip() if nxt else "(see CURRENT_SLICE.md)")]
        eo = [x for x in m.get("execution_order", []) if self.slices.get(x, {}).get("status") == "PLANNED"]
        if eo:
            L += ["", "## Next slices (execution order)", ", ".join(f"{x} ({self.slices[x].get('title')})" for x in eo[:4])]
        L += ["", "## Completed slices", ", ".join(f"{x} ({self.slices[x].get('title')})" for x in done_slices) or "none"]
        bl = [rid for rid, r in self.reqs.items() if r.get("status") == "BLOCKED"]
        L += ["", "## Known blockers"] + ([f"* {x}: {self.reqs[x].get('blocked', '?')}" for x in bl] or ["none"])
        nv = [rid for rid, r in self.reqs.items() if r.get("status") in ("NEEDS_VERIFICATION", "INVALIDATED")]
        if nv:
            L += ["", "## Needs verification / invalidated", ", ".join(nv)]
        gates = [e for e in self.evidence if e.get("kind") == "gate"]
        tests = [e for e in self.evidence if e.get("kind") == "test" and set(ev_reqs(e)) & set(act)]
        L += ["", "## Test status",
              "Summaries trimmed; full text: `python3 tools/capsule.py show <evidence id>`."]
        L += [f"* last gate: {gates[-1]['id']} {gates[-1].get('timestamp', gates[-1].get('date', ''))} {gates[-1]['result']} — {self.brief(gates[-1].get('summary', ''), 480)}"] if gates else [f"* no gate recorded in v{m.get('version')} yet"]
        L += [f"* {e['id']} {e['result']} [{', '.join(ev_reqs(e))}] {self.brief(e.get('summary', ''))}" for e in tests[-3:]]
        benches = [e for e in self.evidence if e.get("kind") == "bench"]
        L += ["", "## Benchmark status"]
        L += [f"* {e['id']} {e['result']} [{', '.join(ev_reqs(e))}] {self.brief(e.get('summary', ''))}" for e in benches[-2:]] or ["* none recorded"]
        for name in ("PERFORMANCE_BASELINE.csv", "BENCH_RESULTS.csv"):
            p = os.path.join(self.dir, name)
            if os.path.exists(p):
                n = max(0, len(read(p).splitlines()) - 1)
                L.append(f"* {name}: {n} rows")
        rows, cerr = self.catalog_counts() if self.catalog else ([], [])
        if self.catalog:
            L += ["", "## Tool catalog", f"{len(rows)} tools; gate deficits: {len(cerr)}"
                  + (f" (first: {cerr[0]})" if cerr else "")]
        L += ["", "## Every slice ends with",
              "implement → targeted test (`capsule.py impact`) → bench if perf → `capsule.py evidence` → "
              "`capsule.py status` → `capsule.py capsule` → commit → write back to the PC + SHA readback "
              "(`tools/sync.py`) → bundle. Full suites only at the gates. Not enough quota for the next "
              "slice: checkpoint and stop.",
              "",
              "## Canonical repository",
              " ".join(m.get("canonical_repo", "").split())]
        if m.get("owner_todo"):
            L += ["", "## Owner to-do"] + [f"* {t}" for t in m["owner_todo"]]
        return "\n".join(L).rstrip() + "\n"


def git_info(root):
    def run(*a):
        return subprocess.run(["git", "-C", root, *a], capture_output=True, text=True).stdout
    ver = "?"
    cp = os.path.join(root, "Cargo.toml")
    if os.path.exists(cp):
        m = re.search(r'^version\s*=\s*"([^"]+)"', read(cp), re.M)
        ver = m.group(1) if m else "?"
    return {"branch": run("rev-parse", "--abbrev-ref", "HEAD").strip() or "?",
            "head": run("rev-parse", "--short", "HEAD").strip() or "?",
            "dirty": [l[3:] for l in run("status", "--porcelain").splitlines() if l.strip()],
            "app_version": ver}


def changed_files(root, base):
    def run(*a):
        return subprocess.run(["git", "-C", root, *a], capture_output=True, text=True).stdout.splitlines()
    files = run("diff", "--name-only", base) + run("ls-files", "--others", "--exclude-standard")
    return sorted(set(f for f in files if f))


def set_status(path, state, ids):
    text = read(path)
    n = 0
    for rid in ids:
        pat = re.compile(r'(^\[req\."?' + re.escape(rid) + r'"?\]\s*\n(?:(?!^\[).*\n)*?^status\s*=\s*)"[A-Z_]+"', re.M)
        text, k = pat.subn(lambda mo: mo.group(1) + f'"{state}"', text, count=1)
        if not k:
            raise SystemExit(f"{rid}: no [req.{rid}] section with a status line")
        n += k
    write(path, text)
    return n


def set_field(path, rid, key, value):
    """Sets `key = value` (TOML-compatible JSON) in [req.rid], replacing an existing line."""
    if not re.fullmatch(r"[a-z_]+", key):
        raise SystemExit(f"bad key {key!r}")
    text = read(path)
    m = re.search(r'^\[req\."?' + re.escape(rid) + r'"?\]\s*\n((?:(?!^\[).*\n)*)', text, re.M)
    if not m:
        raise SystemExit(f"{rid}: no [req.{rid}] section")
    body = m.group(1)
    line = f"{key} = {json.dumps(value, ensure_ascii=False)}\n"
    kl = re.search(r"^" + key + r"\s*=.*\n", body, re.M)
    if kl:
        body = body[:kl.start()] + line + body[kl.end():]
    else:
        st = re.search(r"^status\s*=.*\n", body, re.M)
        at = st.end() if st else 0
        body = body[:at] + line + body[at:]
    text = text[:m.start(1)] + body + text[m.end(1):]
    tomllib.loads(text)  # still valid TOML
    write(path, text)


def add_evidence(plan, reqs, kind, result, summary, test, nums, fixture, git):
    ids = [int(e["id"][1:]) for e in plan.evidence if str(e.get("id", "")).startswith("E")]
    e = {"id": f"E{(max(ids) + 1 if ids else 1):04d}",
         "timestamp": datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%MZ"),
         "requirement_ids": reqs, "kind": kind, "result": result,
         "commit": git["head"], "dirty": bool(git["dirty"]), "summary": summary}
    if test:
        e["test_name"] = test
    if nums:
        e["benchmark"] = nums
    if fixture:
        e["reference_fixture"] = fixture
    with open(os.path.join(plan.dir, "EVIDENCE.jsonl"), "a", encoding="utf-8", newline="\n") as f:
        f.write(json.dumps(e, ensure_ascii=False) + "\n")
    return e


def main(argv=None, root=ROOT):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--dir", default="docs/v1_0_beta2")
    sub = ap.add_subparsers(dest="action", required=True)
    sub.add_parser("check")
    sub.add_parser("capsule")
    sub.add_parser("ready")
    sub.add_parser("slice")
    p = sub.add_parser("show")
    p.add_argument("ids", nargs="+")
    p = sub.add_parser("catalog")
    p.add_argument("--gate", action="store_true")
    p.add_argument("--review", action="store_true", help="shared purposes per family, rubric summary")
    p.add_argument("--registry", help="registry dump from the tool_catalog example")
    p = sub.add_parser("impact")
    p.add_argument("--base", default="HEAD")
    p.add_argument("paths", nargs="*")
    p = sub.add_parser("evidence")
    p.add_argument("--reqs", required=True)
    p.add_argument("--kind", required=True, choices=EVIDENCE_KINDS)
    p.add_argument("--result", required=True, choices=EVIDENCE_RESULTS)
    p.add_argument("--summary", required=True)
    p.add_argument("--test")
    p.add_argument("--fixture")
    p.add_argument("--num", action="append", default=[], help="key=value (numbers parsed)")
    p = sub.add_parser("status")
    p.add_argument("state", choices=REQ_STATES)
    p.add_argument("ids", nargs="+")
    p = sub.add_parser("field")
    p.add_argument("id")
    p.add_argument("key")
    p.add_argument("value")
    a = ap.parse_args(argv)
    plan = Plan(root, a.dir)
    if a.action in ("check", "capsule"):
        errs = plan.check()
        for e in errs:
            print("ERROR", e)
        if errs:
            return 1
        if a.action == "check":
            print(f"ok: {len(plan.reqs)} requirements, {len(plan.slices)} slices, {len(plan.evidence)} evidence, "
                  f"{len(plan.catalog.get('tool', []))} catalog tools")
            return 0
        out = os.path.join(plan.dir, "SESSION_CAPSULE.md")
        write(out, plan.capsule(git_info(root)))
        print("wrote", os.path.relpath(out, root))
        return 0
    if a.action == "ready":
        for rid in plan.ready():
            print(rid, plan.reqs[rid].get("slice"), plan.reqs[rid].get("name"))
        return 0
    if a.action in ("slice", "show"):
        ids = a.ids if a.action == "show" else [r for r, v in plan.reqs.items()
                                                 if v.get("slice") == plan.meta.get("active_slice")]
        evs = {e.get("id"): e for e in plan.evidence}
        bad = [r for r in ids if r not in plan.reqs and r not in evs]
        if bad:
            raise SystemExit(f"unknown requirement(s) / evidence: {bad}")
        print("\n".join(plan.entry(r) if r in plan.reqs
                        else f"{r} {evs[r].get('kind')} {evs[r].get('result')} "
                             f"[{', '.join(ev_reqs(evs[r]))}] {evs[r].get('summary', '')}"
                        for r in ids))
        return 0
    if a.action == "catalog":
        if a.review:
            for line in plan.catalog_review():
                print(line)
            return 0
        rows, errs = plan.catalog_counts()
        if a.registry:
            reg = plan.catalog_vs_registry(read(a.registry))
            for e in reg:
                print("REGISTRY", e)
            if reg:
                return 1
            print(f"registry: {len(rows)} catalog tools consistent with the dump")
            return 0
        for r in rows:
            print(f"{r[0]:<28} {str(r[1]):<20} rule {str(r[2]):<10} active {r[3]:>2} implemented {r[4]:>2}")
        for e in errs:
            print("GATE", e)
        return 1 if (a.gate and errs) else 0
    if a.action == "impact":
        paths = a.paths or changed_files(root, a.base)
        fast, heavy, bench, unmapped = plan.impact_for(paths)
        for p in unmapped:
            print("# unmapped (fallback rule used):", p)
        for c in fast:
            print(c)
        for c in heavy:
            print("# heavy:", c)
        for c in bench:
            print("# bench:", c)
        if not fast and not heavy and not bench:
            print("# no code changes: no tests needed")
        return 0
    if a.action == "evidence":
        reqs = [r for r in a.reqs.split(",") if r]
        bad = [r for r in reqs if r not in plan.reqs]
        if bad:
            raise SystemExit(f"unknown requirement(s): {bad}")
        nums = {}
        for kv in a.num:
            k, v = kv.split("=", 1)
            try:
                nums[k] = float(v) if "." in v or "e" in v.lower() else int(v)
            except ValueError:
                nums[k] = v
        e = add_evidence(plan, reqs, a.kind, a.result, a.summary, a.test, nums, a.fixture, git_info(root))
        print("recorded", e["id"])
        return 0
    if a.action == "field":
        if a.id not in plan.reqs:
            raise SystemExit(f"unknown requirement {a.id}")
        set_field(os.path.join(plan.dir, "REQ_GRAPH.toml"), a.id, a.key, json.loads(a.value))
        print(f"{a.id}.{a.key} set")
        return 0
    if a.action == "status":
        n = set_status(os.path.join(plan.dir, "REQ_GRAPH.toml"), a.state, a.ids)
        print(f"updated {n} requirement(s)")
        return 0
    return 2


