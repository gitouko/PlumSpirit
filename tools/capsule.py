#!/usr/bin/env python3
"""PlumSpirit planning files (v0.9+, contract §009–§015): requirement graph, test
impact, evidence ledger, tool catalog, legacy map, session capsule.

The repository is the project memory. A session reads <dir>/SESSION_CAPSULE.md
(generated here) and <dir>/CURRENT_SLICE.md, then `capsule.py slice` for the
active requirement entries — never the whole contract or the whole graph.

Files (in --dir, default docs/v1_0_beta2; beta1: --dir docs/v1_0_beta1; v0.9: --dir docs/v0_9, which also keeps
the tool catalog and legacy map the engine tests read):
  REQ_GRAPH.toml     [meta], [slice.<id>], [req.<id>] (§010 fields)
  TEST_IMPACT.toml   [[rule]] paths -> fast / heavy / bench commands, [gates.<name>]
  EVIDENCE.jsonl     one JSON object per line (append only, §012 fields)
  TOOL_CATALOG.toml  [[tool]] with [[tool.function]] (§095–§101), validated
  LEGACY_MAP.toml    [[legacy]] / [[removed]] stable-ID migration (§109–§116, §237)
  CURRENT_SLICE.md   hand-written (§013); its "Slice: <id>" line = meta.active_slice
  SESSION_CAPSULE.md generated by `capsule` (§014), never edited by hand
  BENCH_RESULTS.csv, PERFORMANCE_BASELINE.csv  measured numbers (§291, §292)

Commands:
  check                       validate everything (exit 1 on errors)
  capsule                     check, then write SESSION_CAPSULE.md
  slice                       print the active slice's requirement entries in full
  show ID [ID …]              print requirement entries in full
  impact [--base REV] [PATH…] targeted test commands for the given / changed files
  evidence --reqs A,B --kind K --result R --summary S [--test T] [--num k=v …]
           [--fixture F]      append one evidence record
  status STATE ID [ID …]      set requirement status in REQ_GRAPH.toml (in place)
  field ID KEY JSON           set one field of a requirement (JSON value, e.g. '["cargo test x"]')
  ready                       NOT_STARTED requirements whose dependencies are DONE
  catalog [--gate]            tool-catalog counts (--gate: fail unless §253 holds)
Standard library only (Python 3.11+).
"""
